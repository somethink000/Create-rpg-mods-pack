    private static final Object INTERPOLATED = DensityFunctions.interpolated(DensityFunctions.zero()).codec();
    private static final Realm[] REALMS = Realm.values();
    /** Per realm: fluid below its sea level (else air) — its former dimension's default fluid. */
    private static final BlockState[] FLUID = new BlockState[REALMS.length];
    private static final int[] SEA_LEVEL = new int[REALMS.length];
    /** Realms merged into the Overworld this run: their dimensions are not created. */
    private static volatile Set<Realm> merged = EnumSet.noneOf(Realm.class);

    /** The realm world's generator settings (identity: C2ME compiles the router, so its type can't be checked). */
    private static volatile NoiseGeneratorSettings realmSettings;

    public static boolean isRealmSettings(NoiseGeneratorSettings settings) {
        return settings == realmSettings;
    }

    public static boolean isMerged(ResourceKey<?> stemOrLevel) {
        for (Realm realm : merged) {
            if (realm.stem.location().equals(stemOrLevel.location())) {
                return true;
            }
        }
        return false;
    }

    /** The realm a merged dimension became, or null. */
    public static Realm realmOf(ResourceKey<?> stemOrLevel) {
        for (Realm realm : merged) {
            if (realm.stem.location().equals(stemOrLevel.location())) {
                return realm;
            }
        }
        return null;
    }

    /** For a dungeon of the given former dimension placed in this level: its realm, or null if the level isn't the realm world. */
    public static Realm realmFor(Level level, net.minecraft.resources.ResourceLocation dimension) {
        if (!(level instanceof ServerLevel server) || !(server.getChunkSource().getGenerator().getBiomeSource() instanceof RealmBiomeSource)) {
            return null;
        }
        Realm realm = realmOf(ResourceKey.create(Registries.DIMENSION, dimension));
        return realm != null ? realm : Realm.OVERWORLD;
    }

    /** Structures that belong to one lifted realm (all their biomes are that realm's) and that realm's shift. */
    private static volatile java.util.Map<net.minecraft.world.level.levelgen.structure.Structure, Integer> lifts = java.util.Map.of();
    private static final java.util.Map<Integer, ChunkGenerator> LIFTED = new java.util.concurrent.ConcurrentHashMap<>();
    private static volatile ChunkGenerator realmGenerator;
    /** Per shift: that realm's native floor (its generator's min y). */
    private static final java.util.Map<Integer, Integer> NATIVE_MIN_Y = new java.util.concurrent.ConcurrentHashMap<>();
    /** Per shift: that realm's dimension height range (its structures pick heights inside it). */
    private static final java.util.Map<Integer, net.minecraft.world.level.LevelHeightAccessor> NATIVE_HEIGHTS = new java.util.concurrent.ConcurrentHashMap<>();

    /** The height range a structure lays itself out in: for a lifted realm's own structure, that realm's dimension's. */
    public static net.minecraft.world.level.LevelHeightAccessor heightsFor(net.minecraft.world.level.levelgen.structure.Structure structure,
                                                                        net.minecraft.world.level.LevelHeightAccessor heights) {
        int shift = liftOf(structure);
        return shift == 0 ? heights : NATIVE_HEIGHTS.getOrDefault(shift, heights);
    }

    /** The shift a structure is lifted by (0: not a lifted realm's own structure). */
    public static int liftOf(net.minecraft.world.level.levelgen.structure.Structure structure) {
        return lifts.getOrDefault(structure, 0);
    }

    /** The generator a structure lays itself out with: for a lifted realm's own structure, that realm's native heights. */
    public static ChunkGenerator liftedFor(net.minecraft.world.level.levelgen.structure.Structure structure, ChunkGenerator generator) {
        int shift = liftOf(structure);
        if (shift == 0 || generator != realmGenerator || !(generator instanceof NoiseBasedChunkGenerator noise)) {
            return generator;
        }
        return LIFTED.computeIfAbsent(shift, s -> new LiftedGenerator(noise, s, NATIVE_MIN_Y.getOrDefault(s, 0)));
    }

    private static volatile RealmBiomeSource realmBiomes;
    public static final ResourceKey<Biome> TWILIGHT_FLAT = ResourceKey.create(Registries.BIOME,
        net.minecraft.resources.ResourceLocation.fromNamespaceAndPath("twilightforest", "clearing"));

    /**
     * Twilight's terrain reads its biome's depth and scale from its own biome grid at grid cell (quarts of its stretched
     * space). In the realm world it reads the biome of our Twilight cell there instead, so the terrain matches the land's
     * biome (highlands are hills, a swamp lies low); outside Twilight cells a flat clearing, so borders settle down.
     * Null when this isn't the realm world (Twilight's own grid then).
     */
    public static ResourceKey<Biome> twilightTerrainBiome(int gridX, int gridZ) {
        RealmBiomeSource biomes = realmBiomes;
        if (biomes == null || !merged.contains(Realm.TWILIGHT)) {
            return null;
        }
        int scale = 4 * Realm.TWILIGHT.stretch;
        int x = gridX * scale + scale / 2;
        int z = gridZ * scale + scale / 2;
        RealmLayout.Sample sample = RealmLayout.sample(x, z);
        Holder<Biome> biome = sample.first() == Realm.TWILIGHT ? biomes.landAt(Realm.TWILIGHT, sample.cell(), x, z) : null;
        return biome != null ? biome.unwrapKey().orElse(TWILIGHT_FLAT) : TWILIGHT_FLAT;
    }

    /** The realm at a position of a level, or null if the level is not the realm world. */
    public static Realm realmAt(Level level, BlockPos pos) {
        if (level instanceof ServerLevel server ? server.getChunkSource().getGenerator().getBiomeSource() instanceof RealmBiomeSource
            : level.isClientSide() && level.dimension() == Level.OVERWORLD && RealmLayout.known()) {
            return RealmLayout.dominant(pos.getX(), pos.getZ());
        }
        return null;
    }

    /** Clients learn the realm layout (piglins at home in the Nether realm must not shake there). */
    @net.neoforged.bus.api.SubscribeEvent
    static void onLogin(net.neoforged.neoforge.event.entity.player.PlayerEvent.PlayerLoggedInEvent event) {
        if (event.getEntity() instanceof net.minecraft.server.level.ServerPlayer player && !merged.isEmpty()
            && player.connection.hasChannel(net.expedition.net.RealmLayoutPayload.TYPE)) {
            net.neoforged.neoforge.network.PacketDistributor.sendToPlayer(player,
                new net.expedition.net.RealmLayoutPayload(RealmLayout.key(), RealmLayout.realms().stream().map(Realm::ordinal).toList(),
                    RealmLayout.originX(), RealmLayout.originZ()));
        }
    }

    /**
     * Never spawn in the sea, and spawn where the realm layout is centred: if the spawn vanilla picked is water or away
     * from that centre, the dry Overworld land nearest to the centre (by the generator's terrain) becomes the spawn.
     */
    public static void ensureLandSpawn(ServerLevel level) {
        if (!(level.getChunkSource().getGenerator().getBiomeSource() instanceof RealmBiomeSource)) {
            return;
        }
        BlockPos spawn = level.getSharedSpawnPos();
        BlockPos centre = new BlockPos(RealmLayout.originX(), spawn.getY(), RealmLayout.originZ());
        if (isLand(level, spawn.getX(), spawn.getZ()) && spawn.distSqr(centre) < 256 * 256) {
            return;
        }
        for (int radius = 0; radius <= 3000; radius += 32) {
            int points = 8 + radius / 8;
            for (int i = 0; i < points; i++) {
                double angle = Math.PI * 2 * i / points;
                int x = centre.getX() + (int) (Math.cos(angle) * radius);
                int z = centre.getZ() + (int) (Math.sin(angle) * radius);
                if (isLand(level, x, z)) {
                    var source = level.getChunkSource();
                    int y = source.getGenerator().getBaseHeight(x, z, net.minecraft.world.level.levelgen.Heightmap.Types.WORLD_SURFACE_WG, level, source.randomState());
                    level.setDefaultSpawnPos(new BlockPos(x, y, z), 0);
                    Expedition.LOG.info("Spawn {} moved to land at the world's centre: {},{},{}", spawn.toShortString(), x, y, z);
                    return;
                }
            }
        }
        Expedition.LOG.warn("Spawn is in the sea at {} and no land was found within 3000 blocks", spawn.toShortString());
    }

    private static boolean isLand(ServerLevel level, int x, int z) {
        if (RealmLayout.dominant(x, z) != Realm.OVERWORLD) {
            return false;
        }
        var source = level.getChunkSource();
        int ground = source.getGenerator().getBaseHeight(x, z, net.minecraft.world.level.levelgen.Heightmap.Types.OCEAN_FLOOR_WG, level, source.randomState());
        if (ground <= level.getSeaLevel() + 1) {
            return false;
        }
        var biome = source.getGenerator().getBiomeSource().getNoiseBiome(net.minecraft.core.QuartPos.fromBlock(x), net.minecraft.core.QuartPos.fromBlock(ground),
            net.minecraft.core.QuartPos.fromBlock(z), source.randomState().sampler());
        return !biome.is(net.minecraft.tags.BiomeTags.IS_OCEAN) && !biome.is(net.minecraft.tags.BiomeTags.IS_RIVER);
    }

    /** The Overworld's stem with the realm generator; other stems unchanged. */
    public static LevelStem wrapStem(LevelStem stem, RegistryAccess registries, long seed) {
        ChunkGenerator generator = wrap(stem.generator(), registries, seed);
        return generator == stem.generator() ? stem : new LevelStem(stem.type(), generator);
    }

    static ChunkGenerator wrap(ChunkGenerator generator, RegistryAccess registries, long seed) {
        if (!(generator instanceof NoiseBasedChunkGenerator overworld) || generator.getBiomeSource() instanceof RealmBiomeSource) {
            return generator;
        }
        Relief.apply(registries);
        Continents.apply(registries);
        Registry<LevelStem> stems = registries.registryOrThrow(Registries.LEVEL_STEM);
        Map<Realm, NoiseBasedChunkGenerator> generators = new EnumMap<>(Realm.class);
        generators.put(Realm.OVERWORLD, overworld);
        for (Realm realm : REALMS) {
            if (realm != Realm.OVERWORLD && stems.get(realm.stem) instanceof LevelStem stem
                && stem.generator() instanceof NoiseBasedChunkGenerator other) {
                generators.put(realm, other);
            }
        }
        int n = REALMS.length;
        DensityFunction[] finalDensity = new DensityFunction[n];
        DensityFunction[] initialDensity = new DensityFunction[n];
        DensityFunction[] veinToggle = new DensityFunction[n];
        int[] minY = new int[n];
        int[] maxY = new int[n];
        List<SurfaceRules.RuleSource> rules = new ArrayList<>();
        Map<Realm, BiomeSource> sources = new EnumMap<>(Realm.class);
        NoiseGeneratorSettings base = overworld.generatorSettings().value();
        generators.forEach((realm, realmGenerator) -> {
            int i = realm.ordinal();
            NoiseGeneratorSettings settings = realmGenerator.generatorSettings().value();
            NoiseRouter router = settings.noiseRouter();
            finalDensity[i] = gate(realm, router.finalDensity());
            DensityFunction initial = router.initialDensityWithoutJaggedness();
            initialDensity[i] = initial.minValue() == initial.maxValue() && realm != Realm.OVERWORLD ? null : gate(realm, initial);
            minY[i] = settings.noiseSettings().minY();
            if (realm.shift != 0) {
                NATIVE_MIN_Y.put(realm.shift, minY[i]);
                var type = stems.get(realm.stem).type().value();
                NATIVE_HEIGHTS.put(realm.shift, net.minecraft.world.level.LevelHeightAccessor.create(type.minY(), type.height()));
            }
            maxY[i] = settings.noiseSettings().minY() + settings.noiseSettings().height();
            FLUID[i] = settings.defaultFluid();
            SEA_LEVEL[i] = settings.seaLevel();
            Expedition.LOG.info("Realm {}: settings {}, y {}..{}, fluid {} below {}, default {}", realm,
                realmGenerator.generatorSettings().unwrapKey().map(k -> k.location().toString()).orElse("inline"),
                minY[i], maxY[i], FLUID[i], SEA_LEVEL[i], settings.defaultBlock());
            if (realm == Realm.OVERWORLD) {
                veinToggle[i] = router.veinToggle();
                return;
            }
            sources.put(realm, realmGenerator.getBiomeSource());
            @SuppressWarnings("unchecked")
            ResourceKey<Biome>[] biomes = realmGenerator.getBiomeSource().possibleBiomes().stream()
                .flatMap(holder -> holder.unwrapKey().stream()).toArray(ResourceKey[]::new);
            // The realm's own rules, then its stone everywhere else: no Overworld dirt or deepslate inside a realm.
            rules.add(SurfaceRules.ifTrue(SurfaceRules.isBiome(biomes),
                SurfaceRules.sequence(settings.surfaceRule(), SurfaceRules.state(settings.defaultBlock()))));
        });
        // The ice wall behind the world border (RealmTerrain): packed ice veined with blue ice and bare rock, snow on its ledges.
        rules.add(0, SurfaceRules.ifTrue(SurfaceRules.isBiome(ICE_WALL), SurfaceRules.sequence(
            SurfaceRules.ifTrue(SurfaceRules.noiseCondition(net.minecraft.world.level.levelgen.Noises.ICE, 0.35, Double.MAX_VALUE),
                SurfaceRules.state(net.minecraft.world.level.block.Blocks.BLUE_ICE.defaultBlockState())),
            SurfaceRules.ifTrue(SurfaceRules.noiseCondition(net.minecraft.world.level.levelgen.Noises.PACKED_ICE, -0.25, 0.15),
                SurfaceRules.state(net.minecraft.world.level.block.Blocks.STONE.defaultBlockState())),
            SurfaceRules.ifTrue(SurfaceRules.ON_FLOOR, SurfaceRules.state(net.minecraft.world.level.block.Blocks.SNOW_BLOCK.defaultBlockState())),
            SurfaceRules.state(net.minecraft.world.level.block.Blocks.PACKED_ICE.defaultBlockState()))));
        rules.add(base.surfaceRule());
        NoiseRouter router = base.noiseRouter();
        NoiseRouter realmRouter = new NoiseRouter(router.barrierNoise(), router.fluidLevelFloodednessNoise(), router.fluidLevelSpreadNoise(),
            router.lavaNoise(), router.temperature(), router.vegetation(), router.continents(), router.erosion(), router.depth(), router.ridges(),
            new RealmTerrain(initialDensity, minY, maxY, true, 1), new RealmTerrain(finalDensity, minY, maxY, true, 2),
            new RealmTerrain(veinToggle, minY, maxY, false, 0), router.veinRidged(), router.veinGap());
        NoiseGeneratorSettings settings = new NoiseGeneratorSettings(base.noiseSettings(), base.defaultBlock(), base.defaultFluid(), realmRouter,
            SurfaceRules.sequence(rules.toArray(SurfaceRules.RuleSource[]::new)), base.spawnTarget(), base.seaLevel(),
            base.disableMobGeneration(), base.isAquifersEnabled(), base.oreVeinsEnabled(), base.useLegacyRandomSource());
        List<Realm> available = new ArrayList<>(generators.keySet());
        // The disc's middle: (0, 0), where spawn is (its core is always dry land: RealmLayout.SPAWN_CORE).
        BlockPos centre = BlockPos.ZERO;
        RealmLayout.configure(seed, available, centre.getX(), centre.getZ());
        Set<Realm> mergedNow = EnumSet.copyOf(generators.keySet());
        mergedNow.remove(Realm.OVERWORLD);
        merged = mergedNow;
        Expedition.LOG.info("Realm world: the Overworld now carries {}", available);
        realmSettings = settings;
        RealmBiomeSource biomeSource = new RealmBiomeSource(overworld.getBiomeSource(), sources,
            registries.registryOrThrow(Registries.BIOME).getHolderOrThrow(ICE_WALL));
        realmBiomes = biomeSource;
        ChunkGenerator result = new NoiseBasedChunkGenerator(biomeSource, Holder.direct(settings));
        var accessor = (net.expedition.mixin.ChunkGeneratorFeaturesAccessor) result;
        var featureSettings = accessor.expedition$generationSettings();
        List<BiomeSource> realmSources = new ArrayList<>();
        realmSources.add(overworld.getBiomeSource());
        realmSources.addAll(sources.values());
        accessor.expedition$setFeaturesPerStep(net.neoforged.neoforge.common.util.Lazy.of(() -> mergedFeatureOrder(realmSources, featureSettings)));
        net.expedition.world.UnifiedStructures.manage(result);
        realmGenerator = result;
        LIFTED.clear();
        java.util.Map<net.minecraft.world.level.levelgen.structure.Structure, Integer> structureLifts = new java.util.IdentityHashMap<>();
        // A realm's own structure: of its biomes that exist in this world at all (tags often list unused ones), all are
        // that realm's.
        var worldBiomes = biomeSource.possibleBiomes();
        registries.registryOrThrow(Registries.STRUCTURE).forEach(structure -> {
            var present = structure.biomes().stream().filter(worldBiomes::contains).toList();
            for (var entry : sources.entrySet()) {
                var realmBiomes = entry.getValue().possibleBiomes();
                if (entry.getKey().shift != 0 && !present.isEmpty() && present.stream().allMatch(realmBiomes::contains)) {
                    structureLifts.put(structure, entry.getKey().shift);
                }
            }
        });
        lifts = structureLifts;
        var structureRegistry = registries.registryOrThrow(Registries.STRUCTURE);
        Expedition.LOG.info("Realm world: {} structures of lifted realms are lifted with their terrain: {}", structureLifts.size(),
            structureLifts.keySet().stream().map(structure -> String.valueOf(structureRegistry.getKey(structure)))
                .sorted().collect(java.util.stream.Collectors.joining(" ")));
        return result;
    }

    /**
     * The biomes of different dimensions list shared features in different orders, so one order for all of them has
     * cycles. Each realm's own order is valid (it worked as a dimension): the Overworld's comes first, then each realm
     * appends the features it adds, in its own order. A feature shared by two realms keeps the Overworld's slot.
     */
    private static List<net.minecraft.world.level.biome.FeatureSorter.StepFeatureData> mergedFeatureOrder(
            List<BiomeSource> realmSources, java.util.function.Function<Holder<Biome>, net.minecraft.world.level.biome.BiomeGenerationSettings> settings) {
        List<List<net.minecraft.world.level.levelgen.placement.PlacedFeature>> steps = new ArrayList<>();
        for (BiomeSource source : realmSources) {
            var own = net.minecraft.world.level.biome.FeatureSorter.buildFeaturesPerStep(List.copyOf(source.possibleBiomes()),
                biome -> settings.apply(biome).features(), true);
            for (int step = 0; step < own.size(); step++) {
                if (steps.size() <= step) {
                    steps.add(new ArrayList<>());
                }
                List<net.minecraft.world.level.levelgen.placement.PlacedFeature> merged = steps.get(step);
                Set<net.minecraft.world.level.levelgen.placement.PlacedFeature> seen = java.util.Collections.newSetFromMap(new java.util.IdentityHashMap<>());
                seen.addAll(merged);
                for (var feature : own.get(step).features()) {
                    if (seen.add(feature)) {
                        merged.add(feature);
                    }
                }
            }
        }
        return steps.stream().map(features -> new net.minecraft.world.level.biome.FeatureSorter.StepFeatureData(features,
            net.minecraft.Util.createIndexIdentityLookup(features))).toList();
    }

    /** Every interpolated part of a realm's function only computes inside that realm (see {@link RealmTerrain.Gate}). */
    private static DensityFunction gate(Realm realm, DensityFunction function) {
        // A stretched realm is read at single points of its own coarse grid (RealmTerrain.stretched): no interpolation.
        // A lifted realm's y gradients (its floor, roof and slides) are lifted with it; its noises don't care.
        return function.mapAll(f -> {
            if (f instanceof DensityFunctions.MarkerOrMarked marker && marker.codec() == INTERPOLATED) {
                return realm.stretch > 1 ? marker.wrapped() : DensityFunctions.interpolated(new RealmTerrain.Gate(realm, marker.wrapped()));
            }
            if (realm.shift != 0 && realm.stretch == 1 && f.getClass() == Y_GRADIENT) {
                return liftGradient(f, realm.shift);
            }
            return f;
        });
    }

    private static final Class<?> Y_GRADIENT = DensityFunctions.yClampedGradient(0, 1, 0, 1).getClass();

    /** y_clamped_gradient(fromY, toY, a, b) -> the same gradient {@code shift} blocks higher (its record is not public). */
    private static DensityFunction liftGradient(DensityFunction gradient, int shift) {
        try {
            var components = gradient.getClass().getRecordComponents();
            Object[] values = new Object[components.length];
            for (int i = 0; i < components.length; i++) {
                var accessor = components[i].getAccessor();
                accessor.setAccessible(true);
                values[i] = accessor.invoke(gradient);
            }
            return DensityFunctions.yClampedGradient((int) values[0] + shift, (int) values[1] + shift, (double) values[2], (double) values[3]);
        } catch (ReflectiveOperationException e) {
            throw new IllegalStateException("Can't lift a y gradient", e);
        }
    }

    /** Fluids per realm: the Overworld keeps its aquifers, a realm gets its own fluid below its own sea level. */
    public static final class RealmAquifer implements Aquifer {
        private static final BlockState AIR = Blocks.AIR.defaultBlockState();
        private static final BlockState WATER = Blocks.WATER.defaultBlockState();
        private final Aquifer overworld;

        public RealmAquifer(Aquifer overworld) {
            this.overworld = overworld;
        }

        @Override
        public BlockState computeSubstance(DensityFunction.FunctionContext context, double substance) {
            Realm realm = RealmLayout.dominant(context.blockX(), context.blockZ());
            if (realm == Realm.OVERWORLD) {
                return overworld.computeSubstance(context, substance);
            }
            if (substance > 0) {
                return null;
            }
            int i = realm.ordinal();
            return context.blockY() < SEA_LEVEL[i] + realm.shift && FLUID[i] != null ? FLUID[i] : AIR;
        }

        @Override
        public boolean shouldScheduleFluidUpdate() {
            return overworld.shouldScheduleFluidUpdate();
        }
    }
